import { type ReactNode, useState } from "react";
import { ApiError, api } from "../../api";
import { DiffView } from "../../components/diff-view";
import { useAnnounce } from "../../components/live-region";
import { UntrustedText } from "../../components/untrusted-text";
import {
  type BatchDetail,
  enc,
  type PreviewItem,
  type ProposalDoc,
  parsePlanText,
  prettyPlan,
  type Validation,
} from "./model";
import { ErrorNotice, Pill, useAction } from "./parts";
import { IssueList, PlanEditor } from "./plan-editor";
import { RefinementChat } from "./refinement-chat";

interface CardProps {
  readonly proposal: ProposalDoc;
  readonly item: PreviewItem | undefined;
  readonly projectId: string;
  readonly batchVersion: number;
  readonly selected: boolean;
  readonly acknowledged: boolean;
  readonly onSelect: (selected: boolean) => void;
  readonly onAcknowledge: (acknowledged: boolean) => void;
  readonly onChanged: () => Promise<void>;
  readonly onLoadLatest: () => Promise<BatchDetail | null>;
  readonly readOnlyReason: string | null;
}

const stateTones = { proposed: "info", accepted: "success", rejected: "neutral" } as const;

function Provenance({ item }: { item: PreviewItem | undefined }): ReactNode {
  if (!item) return null;
  const { authorship } = item;
  return (
    <ul className="provenance" aria-label="Where this proposal came from">
      <li>
        {authorship.generatedBy ? (
          <Pill label="Generated by the model" tone="info" shape="info" />
        ) : (
          <Pill label="Written by a person" tone="neutral" shape="check" />
        )}
        {authorship.generatedBy ? (
          <>
            {" "}
            model call <code>{authorship.generatedBy}</code>
          </>
        ) : null}
      </li>
      {authorship.humanEdits.length > 0 ? (
        <li>
          Edited by a person {authorship.humanEdits.length} time
          {authorship.humanEdits.length === 1 ? "" : "s"}; last edit{" "}
          <time dateTime={authorship.humanEdits.at(-1)?.at}>
            {authorship.humanEdits.at(-1)?.at}
          </time>
        </li>
      ) : null}
      {authorship.refinedFrom ? (
        <li>
          Produced by chat refinement of <code>{authorship.refinedFrom}</code>
        </li>
      ) : null}
    </ul>
  );
}

function Editor({
  proposal,
  projectId,
  onChanged,
  onLoadLatest,
  onClose,
}: {
  proposal: ProposalDoc;
  projectId: string;
  onChanged: () => Promise<void>;
  onLoadLatest: () => Promise<BatchDetail | null>;
  onClose: () => void;
}): ReactNode {
  const base = prettyPlan(proposal.plan);
  const [text, setText] = useState(base);
  const [version, setVersion] = useState(proposal.version);
  const [validation, setValidation] = useState<Validation | null>(null);
  const [parseError, setParseError] = useState<string | null>(null);
  const [theirs, setTheirs] = useState<{ text: string; version: number } | null>(null);
  const action = useAction();
  const announce = useAnnounce();

  async function save(): Promise<void> {
    const parsed = parsePlanText(text);
    if (parsed.error !== null) return;
    const saved = await action.run(async () => {
      try {
        await api("PATCH", `/proposals/${enc(proposal.id)}`, {
          body: { ...proposal, plan: parsed.plan },
          ifMatch: version,
        });
        return true;
      } catch (error) {
        if (error instanceof ApiError && error.code === "REVISION_CONFLICT") {
          const latest = await onLoadLatest();
          const current = latest?.proposals.find((candidate) => candidate.id === proposal.id);
          if (current) setTheirs({ text: prettyPlan(current.plan), version: current.version });
        }
        throw error;
      }
    });
    if (saved) {
      setTheirs(null);
      announce("Proposal saved.");
      await onChanged();
      onClose();
    }
  }

  const blocked = parseError !== null || (validation !== null && !validation.valid);
  return (
    <div className="proposal-editor">
      <PlanEditor
        label={`Plan for ${proposal.plan.name}`}
        value={text}
        baseText={base}
        onChange={setText}
        projectId={projectId}
        environmentId={null}
        onValidation={(result, error) => {
          setValidation(result);
          setParseError(error);
        }}
      />
      {theirs ? (
        <section
          aria-label="Edit conflict"
          className="banner tone-warning"
          role="alert"
          data-testid="edit-conflict"
        >
          <div>
            <p>
              <strong>Someone changed this proposal while you were editing.</strong> Nothing was
              overwritten. Compare their version with yours, then choose.
            </p>
            <DiffView
              before={theirs.text}
              after={text}
              caption="Their version against your edits"
            />
            <div className="authoring-actions">
              <button
                type="button"
                className="button secondary"
                onClick={() => {
                  setText(theirs.text);
                  setVersion(theirs.version);
                  setTheirs(null);
                  action.clear();
                }}
              >
                Use their version
              </button>
              <button
                type="button"
                className="button"
                onClick={() => {
                  setVersion(theirs.version);
                  setTheirs(null);
                  action.clear();
                }}
              >
                Keep my edits on top of theirs
              </button>
            </div>
          </div>
        </section>
      ) : (
        <ErrorNotice error={action.error} />
      )}
      <div className="authoring-actions">
        <button
          type="button"
          className="button"
          disabled={action.pending || blocked || text === base}
          onClick={() => void save()}
        >
          Save proposal
        </button>
        <button type="button" className="button secondary" onClick={onClose}>
          Close editor
        </button>
      </div>
    </div>
  );
}

export function ProposalCard(props: CardProps): ReactNode {
  const { proposal, item } = props;
  const [editing, setEditing] = useState(false);
  const [refining, setRefining] = useState(false);
  const steps = proposal.plan.steps ?? [];
  const canSelect = proposal.state === "proposed" && (item?.selectable ?? false);
  const duplicates = item?.similar.filter((similar) => similar.exactDuplicate) ?? [];
  const checkId = `select-${proposal.id}`;
  return (
    <article
      className="proposal-card"
      aria-labelledby={`title-${proposal.id}`}
      data-proposal={proposal.id}
    >
      <header>
        <input
          id={checkId}
          type="checkbox"
          checked={props.selected}
          disabled={!canSelect}
          onChange={(event) => props.onSelect(event.target.checked)}
        />
        <h3 id={`title-${proposal.id}`}>
          <label htmlFor={checkId}>
            <UntrustedText value={proposal.plan.name} maxLength={160} />
          </label>
        </h3>
        <Pill
          label={proposal.state[0]?.toUpperCase() + proposal.state.slice(1)}
          tone={stateTones[proposal.state]}
          shape={
            proposal.state === "accepted"
              ? "check"
              : proposal.state === "rejected"
                ? "slash"
                : "clock"
          }
        />
        {item?.validation.semantic === "invalid" || item?.validation.structural === "invalid" ? (
          <Pill label="Invalid" tone="danger" shape="cross" />
        ) : null}
      </header>
      <Provenance item={item} />
      {item?.revision ? (
        <dl className="context" aria-label="Revision that accepting would create">
          <dt>Accepting creates</dt>
          <dd>
            {item.revision.action === "create_test"
              ? `A new test, revision ${item.revision.ordinal}`
              : `Revision ${item.revision.ordinal} of an existing test`}
          </dd>
          <dt>Runner</dt>
          <dd>
            {item.revision.runner} · {item.revision.type}
          </dd>
          <dt>Steps</dt>
          <dd>
            {item.revision.stepCount} steps, {item.revision.assertionCount} assertions
          </dd>
          <dt>Estimated duration</dt>
          <dd>
            {item.revision.estimate.min}–{item.revision.estimate.max} seconds (
            <UntrustedText value={item.revision.estimate.reason} maxLength={200} />)
          </dd>
        </dl>
      ) : null}
      {proposal.requirementRefs.length > 0 ? (
        <p>
          Requirements:{" "}
          {proposal.requirementRefs.map((ref) => (
            <code key={ref}> {ref}</code>
          ))}
        </p>
      ) : null}
      {item ? <IssueList issues={item.validation.issues} /> : null}
      {proposal.warnings.length > 0 ? (
        <ul className="issue-list" aria-label="Warnings from generation">
          {proposal.warnings.map((warning) => (
            <li key={warning}>
              <span className="visually-hidden">Warning: </span>
              <UntrustedText value={warning} maxLength={300} />
            </li>
          ))}
        </ul>
      ) : null}
      {item && item.similar.length > 0 ? (
        <div>
          <p>
            <strong>Similar to existing work</strong>
          </p>
          <ul className="similar" data-testid="similar">
            {item.similar.map((similar) => (
              <li key={`${similar.kind}:${similar.id}`}>
                {similar.exactDuplicate ? (
                  <Pill label="Exact duplicate" tone="warning" shape="warn" />
                ) : (
                  <Pill label="Similar" tone="neutral" shape="info" />
                )}{" "}
                {Math.round(similar.score * 100)}% match with {similar.kind}{" "}
                <UntrustedText value={similar.name} maxLength={120} /> (<code>{similar.id}</code>)
              </li>
            ))}
          </ul>
          {duplicates.length > 0 && props.selected ? (
            <label className="choice">
              <input
                type="checkbox"
                checked={props.acknowledged}
                onChange={(event) => props.onAcknowledge(event.target.checked)}
              />{" "}
              I accept this proposal even though it duplicates{" "}
              <UntrustedText value={duplicates[0]?.name} maxLength={80} />
            </label>
          ) : null}
        </div>
      ) : null}
      <details>
        <summary>
          {steps.length} step{steps.length === 1 ? "" : "s"}
        </summary>
        <ol className="steps">
          {steps.map((step) => (
            <li key={step.id} data-kind={step.kind}>
              <strong>{step.kind}</strong> <code>{step.id}</code>
              <UntrustedText value={JSON.stringify(step)} maxLength={600} block />
            </li>
          ))}
        </ol>
      </details>
      {props.readOnlyReason === null && proposal.state === "proposed" ? (
        <div className="authoring-actions">
          <button type="button" className="button secondary" onClick={() => setEditing(!editing)}>
            {editing ? "Hide editor" : "Edit plan"}
          </button>
          <button type="button" className="button secondary" onClick={() => setRefining(!refining)}>
            {refining ? "Hide chat" : "Refine with chat"}
          </button>
        </div>
      ) : null}
      {editing ? (
        <Editor
          proposal={proposal}
          projectId={props.projectId}
          onChanged={props.onChanged}
          onLoadLatest={props.onLoadLatest}
          onClose={() => setEditing(false)}
        />
      ) : null}
      {refining ? (
        <RefinementChat
          subject={{ kind: "proposal", id: proposal.id, expectedVersion: props.batchVersion }}
          onProduced={() => void props.onChanged()}
        />
      ) : null}
    </article>
  );
}
